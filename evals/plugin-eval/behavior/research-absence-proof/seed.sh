"""Field normalizers for contact data."""
import re


def normalize_phone(raw: str) -> str:
    """Digits only with a leading +; ten-digit numbers get the US country code."""
    digits = re.sub(r"\D", "", raw)
    if len(digits) == 10:
        digits = "1" + digits
    return "+" + digits


def to_e164(raw: str, default_region: str = "US") -> str:
    """E.164 form for contact records. Replaces normalize_phone for new code."""
    digits = re.sub(r"\D", "", raw)
    if default_region == "US" and len(digits) == 10:
        digits = "1" + digits
    return "+" + digits


def normalize_email(raw: str) -> str:
    return raw.strip().lower()


def normalize_postcode(raw: str) -> str:
    return raw.strip().upper().replace(" ", "")
