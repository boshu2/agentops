"""Write generated/validators.py from app/schema.json. Run with `make gen`."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
schema = json.loads((ROOT / "app" / "schema.json").read_text())
kinds = sorted({col["kind"] for col in schema["columns"]})

lines = [
    "# Generated by scripts/gen_validators.py from app/schema.json. Do not edit.",
    "from app.phones import " + ", ".join(f"normalize_{kind}" for kind in kinds),
    "",
    "",
    "def validate_contact(body: dict) -> dict:",
    "    out = dict(body)",
]
for col in schema["columns"]:
    lines.append(f'    out["{col["name"]}"] = normalize_{col["kind"]}(out["{col["name"]}"])')
lines.append("    return out")

out_dir = ROOT / "generated"
out_dir.mkdir(exist_ok=True)
(out_dir / "__init__.py").write_text("")
(out_dir / "validators.py").write_text("\n".join(lines) + "\n")
SEED_EOF

