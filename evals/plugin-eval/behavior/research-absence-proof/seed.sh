"""CSV contact importer. Each column's normalizer is chosen by its kind in schema.json."""
import csv
import json
from pathlib import Path

from app import phones

SCHEMA = json.loads((Path(__file__).parent / "schema.json").read_text())


def _normalizer(kind: str):
    return getattr(phones, "normalize_" + kind)


def import_rows(path: str):
    with open(path, newline="") as fh:
        for row in csv.DictReader(fh):
            yield {
                col["name"]: _normalizer(col["kind"])(row[col["name"]])
                for col in SCHEMA["columns"]
            }
